export const secondsToMs = (s: number) => s * 1_000;
export const minutesToMs = (m: number) => m * 60_000;
export const hoursToMs = (h: number) => h * 3_600_000;
export const daysToMs = (d: number) => d * 86_400_000;

export const minutesToSeconds = (m: number) => m * 60;
export const hoursToSeconds = (h: number) => h * 3_600;
export const daysToSeconds = (d: number) => d * 86_400;
